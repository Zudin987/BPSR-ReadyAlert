//! Compact v1.26 lookup data derived from the supplied DungeonsTable/EquipTable.
//! No network access is used at runtime.

#[derive(Clone, Debug)]
pub struct DungeonMeta {
    pub scene_id: i32,
    pub dungeon_id: i32,
    pub play_type: i32,
    pub difficulty: &'static str,
    pub name: &'static str,
}

#[derive(Clone, Copy, Debug, Default)]
pub struct EquipMeta {
    pub equip_id: i32,
    pub part: i32,
    pub gear_level: i32,
    pub suit_id: i32,
}

static DUNGEONS: std::sync::OnceLock<Vec<DungeonMeta>> = std::sync::OnceLock::new();

fn dungeons() -> &'static [DungeonMeta] {
    DUNGEONS.get_or_init(|| {
        include_str!("../data/dungeons_v1260.tsv")
            .lines()
            .filter(|line| !line.is_empty() && !line.starts_with('#'))
            .filter_map(|line| {
                let mut p = line.splitn(5, '\t');
                let scene_id = p.next()?.parse().ok()?;
                let dungeon_id = p.next()?.parse().ok()?;
                let play_type = p.next()?.parse().ok()?;
                let raw_difficulty = p.next()?.trim();
                let name = p.next()?.trim();
                Some(DungeonMeta {
                    scene_id,
                    dungeon_id,
                    play_type,
                    difficulty: if raw_difficulty.is_empty() {
                        known_difficulty(dungeon_id)
                    } else {
                        leak(raw_difficulty)
                    },
                    name: leak(name),
                })
            })
            .collect()
    })
}

fn leak(value: &str) -> &'static str {
    Box::leak(value.to_string().into_boxed_str())
}

// The complete supplied dungeon table intentionally remains the source of
// scene/name/play-type truth. A prior v1.26 table carried a small set of
// authoritative difficulty labels that were lost when the complete table was
// imported with blank difficulty cells; retain only those known labels here
// rather than guessing for newer/remapped rows.
fn known_difficulty(dungeon_id: i32) -> &'static str {
    match dungeon_id {
        1031 | 1631 | 1121 | 1152 | 1221 | 1233 | 1331 | 1421 | 6007 => "Normal",
        1032 | 1632 | 1122 | 1151 | 1222 | 1234 | 1332 | 1422 | 6008 => "Hard",
        1033 | 1123 | 1150 | 1223 | 1235 | 1333 | 1423 | 1533 | 1633 | 6009 | 6023 => "Master 1",
        _ => "",
    }
}

pub fn dungeon_by_id(id: i32) -> Option<&'static DungeonMeta> {
    dungeons().iter().find(|row| row.dungeon_id == id)
}

pub fn scene_candidates(scene_id: i32) -> Vec<&'static DungeonMeta> {
    dungeons().iter().filter(|row| row.scene_id == scene_id).collect()
}

/// Returns a dungeon id only when the scene mapping is unambiguous.
/// Ambiguous scene ids are intentionally left unresolved instead of guessing.
pub fn unique_dungeon_id_for_scene(scene_id: i32) -> i32 {
    let rows = scene_candidates(scene_id);
    if rows.len() == 1 { rows[0].dungeon_id } else { 0 }
}

pub fn play_type_label(play_type: i32) -> &'static str {
    match play_type {
        2 => "Dungeon",
        3 => "Memory",
        5 => "Race",
        6 => "Event",
        8 => "Unstable",
        9 => "Dungeon",
        12 => "Guild",
        13 => "Guild Hunt",
        15 => "World Boss",
        16 => "Tower",
        17 => "Master Dungeon",
        18 => "Season Challenge",
        19 => "Season Dungeon",
        20 => "Event",
        _ => "Encounter",
    }
}

pub fn slot_name(part: i32) -> &'static str {
    match part {
        200 => "Weapon",
        201 => "Head",
        202 => "Chest",
        203 => "Hands",
        204 => "Boots",
        205 => "Earring",
        206 => "Necklace",
        207 => "Ring",
        208 => "Bracelet (L)",
        209 => "Bracelet (R)",
        210 => "Charm",
        _ => "Equipment",
    }
}

