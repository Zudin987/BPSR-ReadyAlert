pub fn equip_meta(equip_id: i32) -> Option<EquipMeta> {
    EQUIP_RANGES.iter().find_map(|&(first, last, part, gear_level, suit_id)| {
        (equip_id >= first && equip_id <= last).then_some(EquipMeta {
            equip_id,
            part,
            gear_level,
            suit_id,
        })
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_dungeon_scene_resolves() {
        let row = scene_candidates(1151);
        assert_eq!(row.len(), 1);
        assert_eq!(row[0].name, "Void - Towering Ruin");
        assert_eq!(row[0].difficulty, "Hard");
    }

    #[test]
    fn ambiguous_scene_is_not_guessed() {
        assert_eq!(unique_dungeon_id_for_scene(1031), 0);
    }

    #[test]
    fn supplied_equip_metadata_resolves_current_gear() {
        let weapon = equip_meta(2001401).unwrap();
        assert_eq!(weapon.part, 200);
        assert_eq!(weapon.gear_level, 260);
        let raid = equip_meta(2011440).unwrap();
        assert_eq!(raid.suit_id, 102);
    }
}
